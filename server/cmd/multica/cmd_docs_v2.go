func runDocsExport(cmd *cobra.Command, _ []string) error {
	issueID, _ := cmd.Flags().GetString("issue")
	projectID, _ := cmd.Flags().GetString("project")
	sectionID, _ := cmd.Flags().GetString("section")
	workspace, _ := cmd.Flags().GetBool("workspace")
	outputPath, _ := cmd.Flags().GetString("output")

	set := 0
	var urlPath, defaultName string
	if issueID != "" {
		set++
		urlPath = "/api/issues/" + issueID + "/library/export.zip"
		defaultName = "issue-" + issueID + "-library.zip"
	}
	if projectID != "" {
		set++
		urlPath = "/api/projects/" + projectID + "/library/export.zip"
		defaultName = "project-" + projectID + "-library.zip"
	}
	if sectionID != "" {
		set++
		urlPath = "/api/library/sections/" + sectionID + "/export.zip"
		defaultName = "section-" + sectionID + ".zip"
	}
	if workspace {
		set++
		urlPath = "/api/library/export.zip"
		defaultName = "workspace-library.zip"
	}
	if set != 1 {
		return fmt.Errorf("exactly one of --issue, --project, --section, or --workspace is required")
	}
	if outputPath == "" {
		outputPath = defaultName
	}

	client, err := newAPIClient(cmd)
	if err != nil {
		return err
	}

	// Download via the authed client. The existing DownloadFile helper
	// handles relative URL resolution and auth headers correctly (fixed
	// in PR #1585).
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()

	data, err := client.DownloadFile(ctx, urlPath)
	if err != nil {
		return fmt.Errorf("download zip: %w", err)
	}

	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		return fmt.Errorf("create output dir: %w", err)
	}
	if err := os.WriteFile(outputPath, data, 0o644); err != nil {
		return fmt.Errorf("write zip: %w", err)
	}

	fmt.Fprintf(os.Stderr, "Exported %d bytes to %s\n", len(data), outputPath)
	return cli.PrintJSON(os.Stdout, map[string]any{
		"path":  outputPath,
		"bytes": len(data),
	})
}

