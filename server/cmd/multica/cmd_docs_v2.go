// ---------------------------------------------------------------------------
// summarise: writes to the existing curation endpoint with only the summary
// field set. Reuses the COALESCE upsert semantics so other fields stay put.
// ---------------------------------------------------------------------------

func runDocsSummarise(cmd *cobra.Command, args []string) error {
	client, err := newAPIClient(cmd)
	if err != nil {
		return err
	}
	attachmentID := args[0]

	var summary string
	useStdin, _ := cmd.Flags().GetBool("summary-stdin")
	if useStdin {
		data, err := io.ReadAll(os.Stdin)
		if err != nil {
			return fmt.Errorf("read summary from stdin: %w", err)
		}
		summary = string(data)
	} else {
		summary, _ = cmd.Flags().GetString("summary")
	}
	if summary == "" {
		return fmt.Errorf("summary is required (use --summary or --summary-stdin)")
	}

	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()

	var result map[string]any
	payload := map[string]any{"summary": summary}
	if err := client.PutJSON(ctx, "/api/documents/"+attachmentID+"/curation", payload, &result); err != nil {
		return fmt.Errorf("summarise document: %w", err)
	}
	fmt.Fprintln(os.Stderr, "Summary saved for", attachmentID)
	return cli.PrintJSON(os.Stdout, result)
}

func runDocsListUnsummarised(cmd *cobra.Command, _ []string) error {
	client, err := newAPIClient(cmd)
	if err != nil {
		return err
	}
	issueID, _ := cmd.Flags().GetString("issue")
	projectID, _ := cmd.Flags().GetString("project")

	path := "/api/documents/unsummarised"
	if issueID != "" && projectID != "" {
		return fmt.Errorf("provide --issue OR --project, not both")
	}
	if issueID != "" {
		path += "?issue_id=" + issueID
	} else if projectID != "" {
		path += "?project_id=" + projectID
	}

	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()

	var result map[string]any
	if err := client.GetJSON(ctx, path, &result); err != nil {
		return fmt.Errorf("list unsummarised: %w", err)
	}

	output, _ := cmd.Flags().GetString("output")
	if output == "table" {
		docs, _ := result["documents"].([]any)
		headers := []string{"ATTACHMENT ID", "FILENAME", "TYPE", "SIZE"}
		rows := make([][]string, 0, len(docs))
		for _, d := range docs {
			doc, _ := d.(map[string]any)
			if doc == nil {
				continue
			}
			rows = append(rows, []string{
				truncateID(strVal(doc, "attachment_id")),
				strVal(doc, "filename"),
				strVal(doc, "content_type"),
				fmt.Sprintf("%v", doc["size_bytes"]),
			})
		}
		cli.PrintTable(os.Stdout, headers, rows)
		return nil
	}
	return cli.PrintJSON(os.Stdout, result)
}

